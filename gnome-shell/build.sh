set -euo pipefail

THEME_DIR="$(cd "$(dirname "$0")" && pwd)"
VERSION=51
if [[ "${1:-}" == --shell-version ]]; then
    VERSION="${2:-}"
    shift 2
fi
if [[ "$VERSION" != 46 && "$VERSION" != 51 ]]; then
    echo 'ERROR: supported Shell versions are 46 and 51.' >&2
    exit 1
fi
TARGET="${1:-$THEME_DIR/gnome-shell.css}"
if [[ "$VERSION" == 46 && $# -eq 0 ]]; then
    TARGET="$THEME_DIR/gnome-shell-46.css"
fi
if ! command -v sassc >/dev/null 2>&1; then
    echo 'ERROR: sassc is required to rebuild the GNOME Shell theme.' >&2
    echo 'Install with: sudo apt install sassc (Debian/Ubuntu), or sudo pacman -S sassc (Arch).' >&2
    exit 1
fi

TEMP_CSS="$(mktemp)"
TEMP_OUTPUT="$(mktemp)"
trap 'rm -f "$TEMP_CSS" "$TEMP_OUTPUT"' EXIT
SOURCE="$THEME_DIR/sass/gnome-shell.scss"
ASSETS=assets/
if [[ "$VERSION" == 46 ]]; then
    SOURCE="$THEME_DIR/sass/gnome-shell-46.scss"
    ASSETS=assets/46/
fi
sassc -t expanded "$SOURCE" "$TEMP_CSS"
{
    cat <<NOTICE
/* Adwaita-AMOLED GNOME Shell $VERSION theme; modified 2026-10-17.
 * Generated by gnome-shell/build.sh from the bundled Sass sources.
 * SPDX-License-Identifier: GPL-2.0-or-later
 * Upstream copyright and license notice retained below.
 */
NOTICE
    # Ship matching assets instead of depending on a system theme resource.
    sed "s|resource:///org/gnome/shell/theme/|$ASSETS|g" "$TEMP_CSS"
} > "$TEMP_OUTPUT"
chmod 644 "$TEMP_OUTPUT"
mv "$TEMP_OUTPUT" "$TARGET"
if [[ "$VERSION" == 51 && $# -eq 0 ]]; then
    cp "$TARGET" "$THEME_DIR/gnome-shell-51.css"
fi
echo "Built $TARGET"
